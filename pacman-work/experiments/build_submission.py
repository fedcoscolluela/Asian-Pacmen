"""
Bundle the chosen approach into ONE self-contained my_team.py (no sibling imports), so the
tournament loader cannot be confused by helper modules or sys.path order.

usage (from pacman-work/):  python experiments/build_submission.py a2_astar submission/my_team.py
The bundle = upf_fc_core.py + the dependency chain of the chosen agent file, with the
local `from upf_fc_core/a2_astar/... import` lines removed.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AG = os.path.join(ROOT, 'agents')
DEPS = {'a1_reflex': [], 'a2_astar': [], 'a3_alphabeta': ['a2_astar'], 'a4_mcts': ['a2_astar', 'a3_alphabeta'],
        'a6_iw': ['a2_astar'], 'a3_ab_offense_only': ['a2_astar', 'a3_alphabeta'],
        'a7_width': ['a2_astar', 'a6_iw']}
LOCAL = ('upf_fc_core', 'a1_reflex', 'a2_astar', 'a3_alphabeta', 'a4_mcts', 'a6_iw', 'a7_width')


def strip(src, drop_create_team):
    out = []
    for line in src.splitlines():
        if re.match(r'\s*from (%s) import' % '|'.join(LOCAL), line):
            continue
        if line.startswith('sys.path.append(os.path.dirname'):
            continue
        out.append(line)
    text = '\n'.join(out)
    if drop_create_team:
        text = re.sub(r'\ndef create_team\(.*?\n(?=\n\S|\Z)', '\n', text, flags=re.S)
    return text


def main():
    name, dest = sys.argv[1], sys.argv[2]
    parts = ['upf_fc_core'] + DEPS[name] + [name]
    chunks = ['# my_team.py -- generated by experiments/build_submission.py from: ' + ', '.join(parts),
              '# (edit the sources in agents/ and rebuild, do not edit this file by hand)',
              'import os', 'import sys']
    for p in parts:
        src = open(os.path.join(AG, p + '.py')).read()
        chunks.append(f'\n# {"=" * 30} {p}.py {"=" * 30}\n')
        chunks.append(strip(src, drop_create_team=(p != name)))
    os.makedirs(os.path.dirname(os.path.abspath(dest)), exist_ok=True)
    with open(dest, 'w') as f:
        f.write('\n'.join(chunks) + '\n')
    print('wrote', dest)


if __name__ == '__main__':
    main()
